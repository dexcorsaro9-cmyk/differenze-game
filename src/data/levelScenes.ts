/** Every level has a bespoke photograph, so a missing id is a data error, not a fallback. */
export function getLevelScene(levelId: Level['id']): string {
  const scene = LEVEL_SCENES[levelId];
  if (!scene) {
    throw new Error(`No scene photograph registered for level ${levelId}`);
  }
  return scene;
}
